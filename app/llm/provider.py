"""
LLM Provider abstraction.
Supports OpenAI, Google Gemini, and a robust deterministic Grounded Synthesizer
for offline/zero-API key environments and automated testing.
"""

import logging
from abc import ABC, abstractmethod
from typing import List, Dict, Any
from app.config import settings
from app.llm.prompts import CLINICAL_GROUNDING_SYSTEM_PROMPT

logger = logging.getLogger(__name__)


class BaseLLMProvider(ABC):
    @abstractmethod
    def generate_response(self, system_prompt: str, user_prompt: str) -> str:
        """Generate a response given a system prompt and user context prompt."""
        pass


class OpenAILLMProvider(BaseLLMProvider):
    def __init__(self, api_key: str, model_name: str):
        self.api_key = api_key
        self.model_name = model_name

    def generate_response(self, system_prompt: str, user_prompt: str) -> str:
        import requests
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model_name,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            "temperature": 0.1,
        }
        resp = requests.post("https://api.openai.com/v1/chat/completions", json=payload, headers=headers, timeout=30)
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"]


class GeminiLLMProvider(BaseLLMProvider):
    def __init__(self, api_key: str, model_name: str):
        self.api_key = api_key
        self.model_name = model_name

    def generate_response(self, system_prompt: str, user_prompt: str) -> str:
        import requests
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {"parts": [{"text": f"{system_prompt}\n\n{user_prompt}"}]}
            ],
            "generationConfig": {"temperature": 0.1},
        }
        resp = requests.post(url, json=payload, timeout=30)
        resp.raise_for_status()
        candidates = resp.json().get("candidates", [])
        if candidates:
            return candidates[0]["content"]["parts"][0]["text"]
        return "No response generated by Gemini."


class DeterministicGroundedProvider(BaseLLMProvider):
    """
    Deterministic rule-based synthesizer used for testing, zero-cost offline runs,
    and strict context grounding verification without external API keys.
    """

    def generate_response(self, system_prompt: str, user_prompt: str) -> str:
        # Extract sections from user_prompt
        graph_part = ""
        vector_part = ""
        question = ""

        if "QUESTION:" in user_prompt:
            parts = user_prompt.split("=== STRUCTURED KNOWLEDGE GRAPH CONTEXT ===")
            question = parts[0].replace("QUESTION:", "").strip()
            if len(parts) > 1:
                sub_parts = parts[1].split("=== RETRIEVED SYNTHETIC CLINICAL DOCUMENT CHUNKS ===")
                graph_part = sub_parts[0].strip()
                if len(sub_parts) > 1:
                    vector_part = sub_parts[1].split("INSTRUCTIONS:")[0].strip()

        has_graph = graph_part and "No direct knowledge graph relationships found." not in graph_part
        has_vector = vector_part and "No relevant document chunks retrieved." not in vector_part

        if not has_graph and not has_vector:
            return (
                f"Based on the provided synthetic clinical records, no matching information "
                f"was found for the inquiry: '{question}'.\n\n"
                f"Note: This system relies solely on ingested synthetic trial records."
            )

        lines = [
            f"### Clinical Synthesis for: {question}",
            "",
            "#### 1. Structured Knowledge Graph Relationships",
        ]

        if has_graph:
            lines.append("The following factual relationships were retrieved from the domain ontology knowledge graph:")
            for line in graph_part.split("\n"):
                if line.strip():
                    lines.append(f"- {line.strip()}")
        else:
            lines.append("- No direct graph relationships identified.")

        lines.extend([
            "",
            "#### 2. Clinical Document Evidence & Outcomes",
        ])

        if has_vector:
            lines.append("The following findings were extracted from the synthetic clinical trial dossiers:")
            for chunk_block in vector_part.split("\n\n"):
                chunk_block_clean = chunk_block.strip()
                if chunk_block_clean:
                    lines.append(f"- {chunk_block_clean[:350]}...")
        else:
            lines.append("- No narrative document chunks met the relevance threshold.")

        lines.extend([
            "",
            "#### 3. Grounded Conclusion",
            "Synthesizing the structured graph triples with the trial document evidence confirms the documented "
            "clinical evaluations, therapeutic targets, and safety profile without unsupported external claims.",
        ])

        return "\n".join(lines)


def get_llm_provider() -> BaseLLMProvider:
    """Factory to retrieve configured LLM provider."""
    provider_name = settings.llm_provider.lower()

    if provider_name == "openai" and settings.openai_api_key:
        return OpenAILLMProvider(settings.openai_api_key, settings.openai_model)
    elif provider_name == "gemini" and settings.gemini_api_key:
        return GeminiLLMProvider(settings.gemini_api_key, settings.gemini_model)
    else:
        return DeterministicGroundedProvider()
